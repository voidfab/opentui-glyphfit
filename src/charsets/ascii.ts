/**
 * Printable ASCII charset (0x20–0x7E).
 *
 * Shape vectors are derived from the structural/geometric properties of each
 * character — the stroke directions and coverage regions — not from any
 * specific font rendering. This is a cleanroom approximation.
 *
 * Classification approach:
 *   - Diagonal characters (/\X): high coverage in crossing cells
 *   - Horizontal characters (-_=~): strong mid or bot row, symmetric columns
 *   - Vertical characters (|!Il): column-symmetric, all rows similar
 *   - Dense characters (@#MW%): uniformly high across all samples
 *   - Sparse characters (.,;:'`): low-coverage, localised to one region
 *   - Medium-body letters: approximated from dominant stroke geometry
 *
 * Values represent approximate visual weight at each sample point,
 * not measured from any specific font.
 */

